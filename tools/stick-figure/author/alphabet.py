"""Single-line capital letters for ankle-only toe tracing, in a [-1, 1] box."""
import math

def arc(start, end, count=12, rx=1, ry=1):
    return [(rx * math.cos(math.radians(start + (end - start) * i / count)),
             ry * math.sin(math.radians(start + (end - start) * i / count))) for i in range(count + 1)]

